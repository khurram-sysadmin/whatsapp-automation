import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const compile=(source,target)=>fs.writeFileSync(target,ts.transpileModule(fs.readFileSync(source,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
fs.mkdirSync('release-local',{recursive:true});
compile('src/saas/campaignProgressCounts.ts','release-local/progress-test.mjs');
compile('src/saas/voiceRecording.ts','release-local/voice-test.mjs');
const {campaignProgress}=await import('../release-local/progress-test.mjs');
const {encodeVoiceNote,MAX_RECORDING_SECONDS}=await import('../release-local/voice-test.mjs');
const ongoing=campaignProgress({sent:10,delivered:8,read:3,queued:17,sending:1,failed:2,replied:7},'running');
assert.deepEqual(ongoing,{sent:10,failed:2,queued:18,needsReview:0,total:30,processed:12,percent:40});
const uncertain=campaignProgress({sent:29,needsReview:1},'running');
assert.equal(uncertain.percent,97);assert.equal(uncertain.needsReview,1);
const complete=campaignProgress({sent:28,failed:2,delivered:20,read:12},'completed');
assert.equal(complete.percent,100);assert.equal(complete.total,30);
assert.equal(campaignProgress({},'draft').percent,0);
assert.equal(MAX_RECORDING_SECONDS,300);
const samples=Float32Array.from({length:44100},(_,i)=>Math.sin(i*2*Math.PI*440/44100)*.25);
const mp3=await encodeVoiceNote(samples,44100);
const cancelled=new AbortController();cancelled.abort();await assert.rejects(encodeVoiceNote(samples,44100,cancelled.signal),error=>error.name==='AbortError');
assert.equal(mp3.type,'audio/mpeg');assert.ok(mp3.size>1000&&mp3.size<20000);
const bytes=new Uint8Array(await mp3.arrayBuffer());assert.equal(bytes[0],0xff);assert.equal(bytes[1]&0xe0,0xe0);
fs.writeFileSync('release-local/synthetic-voice.mp3',bytes);
console.log('PASS: MP3 encoding, 30-message progress, no delivered/read double counting, unknown delivery visibility and terminal completion. Synthetic audio only.');
